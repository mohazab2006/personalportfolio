#!/usr/bin/env node
/**
 * Seals the root easter egg.
 *
 *   node scripts/seal-root-egg.mjs "your secret passphrase" ["optional message line 1" "line 2" ...]
 *
 * Writes lib/rootEggSeal.ts containing ONLY a salt, an IV and ciphertext. The passphrase itself is
 * never stored anywhere (not even as a hash): the site derives a key from whatever the visitor types
 * (PBKDF2-SHA256, 150k rounds) and tries to decrypt. Wrong phrase = AES-GCM auth failure = nothing.
 *
 * Pick something long and personal (4+ words). Normalisation: trimmed, lower-cased, spaces collapsed.
 */
import { webcrypto as crypto } from 'node:crypto'
import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const ITERATIONS = 150_000
const [, , passphrase, ...lines] = process.argv

if (!passphrase || passphrase.trim().length < 12) {
  console.error('usage: node scripts/seal-root-egg.mjs "a long passphrase (12+ chars)" ["message line" ...]')
  process.exit(1)
}

const normalize = (s) => s.trim().toLowerCase().replace(/\s+/g, ' ')

// The vault's words live in a local, git-ignored file so they never appear in the public repo.
// Copy scripts/vault-content.example.json → scripts/vault-content.local.json and edit it.
const contentPath = path.join(path.dirname(fileURLToPath(import.meta.url)), 'vault-content.local.json')
if (!existsSync(contentPath)) {
  console.error('missing scripts/vault-content.local.json (copy vault-content.example.json and fill it in)')
  process.exit(1)
}
const content = JSON.parse(readFileSync(contentPath, 'utf8'))
const payload = {
  sealedAt: new Date().toISOString().slice(0, 10),
  lines: lines.length ? lines : content.lines,
  vault: content.vault,
}

const enc = new TextEncoder()
const salt = crypto.getRandomValues(new Uint8Array(16))
const iv = crypto.getRandomValues(new Uint8Array(12))
const baseKey = await crypto.subtle.importKey('raw', enc.encode(normalize(passphrase)), 'PBKDF2', false, ['deriveKey'])
const key = await crypto.subtle.deriveKey(
  { name: 'PBKDF2', salt, iterations: ITERATIONS, hash: 'SHA-256' },
  baseKey,
  { name: 'AES-GCM', length: 256 },
  false,
  ['encrypt']
)
const ct = new Uint8Array(await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, enc.encode(JSON.stringify(payload))))

const b64 = (u8) => Buffer.from(u8).toString('base64')
const out = `// Generated by scripts/seal-root-egg.mjs. Do not edit by hand.
// Contains no passphrase and no hash of it: just enough to decrypt when the right phrase is typed.
export const ROOT_EGG_SEAL = {
  iterations: ${ITERATIONS},
  salt: '${b64(salt)}',
  iv: '${b64(iv)}',
  ciphertext: '${b64(ct)}',
} as const
`
const here = path.dirname(fileURLToPath(import.meta.url))
writeFileSync(path.join(here, '..', 'lib', 'rootEggSeal.ts'), out)
console.log('sealed → lib/rootEggSeal.ts (passphrase not stored)')
